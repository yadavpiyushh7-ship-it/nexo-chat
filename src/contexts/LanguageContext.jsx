const LanguageContext = createContext({
  language: 'en',
  setLanguage: () => {},
  t: (key) => BASE_EN[key] || key,
  isRtl: false,
  currentLanguageObj: GLOBAL_LANGUAGES[0],
  localizeChat: (chat) => chat,
  localizeMessageText: (msg) => msg?.text || '',
  translateMessageText: async (text) => text,
});

export function LanguageProvider({ children }) {
  const [language, setLanguageState] = useState(() => {
    try {
      return localStorage.getItem('nexo_app_language') || 'en';
    } catch {
      return 'en';
    }
  });

  const setLanguage = (code) => {
    setLanguageState(code);
    try {
      localStorage.setItem('nexo_app_language', code);
    } catch {}
  };

  const langObj = ALL_LANGUAGES.find((l) => l.code === language) || GLOBAL_LANGUAGES[0];
  const isRtl = Boolean(langObj?.rtl);

  useEffect(() => {
    if (typeof document !== 'undefined') {
      document.documentElement.dir = isRtl ? 'rtl' : 'ltr';
      document.documentElement.lang = language;
    }
  }, [language, isRtl]);

  const dict = TRANSLATIONS[language] || BASE_EN;

  const t = (key, fallback) => {
    return dict[key] || BASE_EN[key] || fallback || key;
  };

  const localizeChat = (chat) => {
    if (!chat) return chat;
    if (chat.id === 'self_vault') {
      return {
        ...chat,
        subtitle: t('vaultSubtitle'),
      };
    }
    if (chat.id === 'chat_placement_cell') {
      return {
        ...chat,
        name: t('placementCellTitle'),
        subtitle: t('placementCellSub'),
      };
    }
    if (chat.id === 'chat_dsa_squad') {
      return {
        ...chat,
        name: t('dsaSquadTitle'),
        subtitle: t('dsaSquadSub'),
      };
    }
    if (chat.id === 'chat_placement_bot') {
      return {
        ...chat,
        name: t('placementBotTitle'),
        subtitle: t('placementBotSub'),
      };
    }
    return chat;
  };

  const localizeMessageText = (msg) => {
    if (!msg) return '';
    const key = SYSTEM_MESSAGE_ID_TO_KEY[msg.id];
    if (key) {
      return t(key, msg.text);
    }
    return msg.text || '';
  };

  const translateMessageText = async (rawText) => {
    if (!rawText || !rawText.trim()) return '';
    const translated = await requestAI({
      mode: 'rewrite',
      tone: 'Natural',
      language: langObj?.name || 'English',
      text: rawText,
    });
    return translated || rawText;
  };

  return (
    <LanguageContext.Provider
      value={{
        language,
        setLanguage,
        t,
        isRtl,
        currentLanguageObj: langObj,
        localizeChat,
        localizeMessageText,
        translateMessageText,
      }}
    >
      {children}
    </LanguageContext.Provider>
  );
}

export function useLanguage() {
  return useContext(LanguageContext);
}
